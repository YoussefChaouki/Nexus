# ---------------------------------------------------------------------------
# Data shape
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class _PatternToIngest:
    """In-memory view of a row before the embedding has been computed."""

    source_type: str
    pattern_id: str
    name: str
    pattern_text: str
    metadata: dict[str, Any]


# ---------------------------------------------------------------------------
# Source builders
# ---------------------------------------------------------------------------


def owasp_patterns() -> list[_PatternToIngest]:
    """Return the OWASP LLM Top 10 (2023) entries as ingestable patterns."""
    return [
        _PatternToIngest(
            source_type="owasp_llm",
            pattern_id=entry["pattern_id"],
            name=entry["name"],
            pattern_text=entry["pattern_text"],
            metadata={"version": "2023"},
        )
        for entry in OWASP_LLM_TOP10_2023
    ]


def atlas_patterns(stix_path: Path | None = None) -> list[_PatternToIngest]:
    """Return MITRE ATLAS techniques as ingestable patterns.

    Args:
        stix_path: Optional override for the STIX bundle location.
            Defaults to ``$ATLAS_STIX_PATH`` then ``data/atlas/ATLAS.json``
            relative to the repository root.
    """
    path = stix_path or _default_atlas_path()
    if not path.is_file():
        logger.warning(
            "atlas_bundle_missing",
            path=str(path),
            hint="download ATLAS.json — see mcp_servers/atlas/README.md",
        )
        return []

    techniques = _load_atlas_techniques(path)
    return [
        _PatternToIngest(
            source_type="atlas",
            pattern_id=t.technique_id,
            name=t.name,
            pattern_text=f"{t.name}. {t.description}",
            metadata={
                "tactic": t.tactic,
                "url": t.url,
                "mitigations": list(t.mitigations),
            },
        )
        for t in techniques
    ]


def _default_atlas_path() -> Path:
    """Resolve the ATLAS STIX bundle location, matching the MCP server."""
    override = os.environ.get("ATLAS_STIX_PATH")
    if override:
        return Path(override).expanduser().resolve()
    return Path(__file__).resolve().parent.parent / "data" / "atlas" / "ATLAS.json"


def _load_atlas_techniques(path: Path) -> list[Any]:
    """Reuse the ATLAS MCP STIX loader without polluting sys.path globally."""
    loader_dir = Path(__file__).resolve().parent.parent / "mcp_servers" / "atlas"
    added = False
    if str(loader_dir) not in sys.path:
        sys.path.insert(0, str(loader_dir))
        added = True
    try:
        from stix_loader import load_atlas_techniques  # type: ignore[import-not-found]
    finally:
        if added:
            sys.path.remove(str(loader_dir))
    return list(load_atlas_techniques(path))


# ---------------------------------------------------------------------------
# Embeddings
# ---------------------------------------------------------------------------


_EMBED_BATCH_SIZE = 100


async def compute_embeddings(
    texts: Sequence[str],
    *,
    model: str,
    api_key: str,
    batch_size: int = _EMBED_BATCH_SIZE,
) -> list[list[float]]:
    """Embed ``texts`` with the OpenAI embeddings endpoint in batches.

    Args:
        texts: Documents to embed.
        model: Embedding model identifier (e.g. ``text-embedding-3-small``).
        api_key: OpenAI API key.
        batch_size: Maximum number of texts per request.

    Returns:
        One embedding vector per input text, preserving order.
    """
    from openai import AsyncOpenAI

    client = AsyncOpenAI(api_key=api_key)
    embeddings: list[list[float]] = []
    for batch in _chunked(texts, batch_size):
        response = await client.embeddings.create(model=model, input=list(batch))
        embeddings.extend([item.embedding for item in response.data])
    return embeddings


def _chunked(items: Sequence[str], size: int) -> Iterable[Sequence[str]]:
    for i in range(0, len(items), size):
        yield items[i : i + size]


# ---------------------------------------------------------------------------
# Database upsert
# ---------------------------------------------------------------------------


_UPSERT_SQL = """
INSERT INTO threat_patterns (
    id, source_type, pattern_id, name, pattern_text, metadata, embedding
) VALUES ($1, $2, $3, $4, $5, $6::jsonb, $7::vector)
ON CONFLICT (pattern_id) DO UPDATE SET
    source_type = EXCLUDED.source_type,
    name = EXCLUDED.name,
    pattern_text = EXCLUDED.pattern_text,
    metadata = EXCLUDED.metadata,
    embedding = EXCLUDED.embedding
RETURNING (xmax = 0) AS inserted
"""


async def upsert_patterns(
    pool: Any,
    patterns: Sequence[_PatternToIngest],
    embeddings: Sequence[Sequence[float]],
) -> tuple[int, int]:
    """Upsert ``patterns`` with their embeddings, returning (inserted, refreshed).

    The ``RETURNING (xmax = 0) AS inserted`` trick distinguishes brand-new
    rows (``xmax = 0``) from rows that existed before this transaction —
    a standard PostgreSQL idiom that lets the script report progress
    without an extra SELECT.
    """
    if len(patterns) != len(embeddings):
        raise ValueError(
            f"pattern/embedding length mismatch: {len(patterns)} vs {len(embeddings)}",
        )

    inserted = 0
    refreshed = 0
    async with pool.acquire() as conn:
        async with conn.transaction():
            for pattern, embedding in zip(patterns, embeddings, strict=True):
                row = await conn.fetchrow(
                    _UPSERT_SQL,
                    str(uuid4()),
                    pattern.source_type,
                    pattern.pattern_id,
                    pattern.name,
                    pattern.pattern_text,
                    json.dumps(pattern.metadata),
                    _vector_literal(embedding),
                )
                if row is not None and row["inserted"]:
                    inserted += 1
                else:
                    refreshed += 1
    return inserted, refreshed


def _vector_literal(embedding: Sequence[float]) -> str:
    """Render an embedding as the pgvector literal ``[v1,v2,...]``."""
    return "[" + ",".join(f"{x:.8f}" for x in embedding) + "]"


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


async def main() -> None:
    """Run the full ingestion pipeline."""
    settings = get_settings()
    patterns = owasp_patterns() + atlas_patterns()
    if not patterns:
        logger.warning("ingest_no_patterns", reason="no sources resolved")
        return

    logger.info(
        "ingest_start",
        owasp=len(OWASP_LLM_TOP10_2023),
        atlas=len(patterns) - len(OWASP_LLM_TOP10_2023),
    )
    embeddings = await compute_embeddings(
        [p.pattern_text for p in patterns],
        model=settings.embedding_model,
        api_key=settings.openai_api_key.get_secret_value(),
    )

    pool = await asyncpg.create_pool(dsn=settings.postgres_dsn, min_size=1, max_size=4)
    try:
        inserted, refreshed = await upsert_patterns(pool, patterns, embeddings)
    finally:
        await pool.close()

    print(  # noqa: T201 — script output is the user-facing summary
        f"{inserted} patterns ingested, {refreshed} already existed",
    )
    logger.info("ingest_done", inserted=inserted, refreshed=refreshed)


if __name__ == "__main__":
    asyncio.run(main())
