"""Ingest the Threat Pattern Library into pgvector (semantic memory).

Sources:

1. **MITRE ATLAS techniques** parsed from the STIX 2.1 bundle
   (``data/atlas/ATLAS.json`` by default; overridable via
   ``ATLAS_STIX_PATH``). The same loader the ATLAS MCP server uses is
   reused so the two stay consistent.

2. **OWASP LLM Top 10 (2023)** — hardcoded below. Source:
   https://owasp.org/www-project-top-10-for-large-language-model-applications/

For every pattern we compute a 1536-dim ``text-embedding-3-small``
embedding and upsert into the ``threat_patterns`` table. The upsert is
keyed by ``pattern_id`` (UNIQUE) so re-running the script is idempotent:
existing patterns get their embedding/metadata refreshed, new ones are
inserted.

Run:

    python scripts/ingest_patterns.py

The script prints two counters:
* *Inserted* — patterns absent before this run.
* *Refreshed* — patterns already present whose embedding was updated.
"""

